    private void btnAddCurriculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddCurriculoActionPerformed
        JFileChooser explorador = new JFileChooser();
        FileNameExtensionFilter filtro = new FileNameExtensionFilter("Documentos (PDF, DOCX, TXT)", "pdf", "docx", "txt");
        explorador.setFileFilter(filtro);
        
        int op = explorador.showOpenDialog(this);
        
        if(op == JFileChooser.APPROVE_OPTION){
            try{
                File arqCurriculo = explorador.getSelectedFile();
                byte[] bytesCurriculo = Files.readAllBytes(arqCurriculo.toPath());
                lblCurriculo.setText("Currículo adicionado.");
                
                pessoa.setCurriculo(bytesCurriculo);
            }
            catch(Exception e){
                JOptionPane.showConfirmDialog(this, e.getMessage());
            }
        }
        
    }//GEN-LAST:event_btnAddCurriculoActionPerformed

    private void btnAddFotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddFotoActionPerformed
        JFileChooser explorador = new JFileChooser();
        FileNameExtensionFilter filtro = new FileNameExtensionFilter("Imagens (JPG, PNG)", "jpg", "jpeg", "png");
        explorador.setFileFilter(filtro);
        explorador.setAcceptAllFileFilterUsed(false);
        
        int op = explorador.showOpenDialog(this);
        
        if(op == JFileChooser.APPROVE_OPTION){
            try{
                File arqFoto = explorador.getSelectedFile();
                byte[] bytesFoto = Files.readAllBytes(arqFoto.toPath());
                ImageIcon image = new ImageIcon(bytesFoto);
                
                int largura = lblFoto.getWidth() > 0 ? lblFoto.getWidth() : 150;
                int altura = lblFoto.getHeight() > 0 ? lblFoto.getHeight() : 150;

                Image imgRedimensionada = image.getImage().getScaledInstance(
                    largura, 
                    altura, 
                    Image.SCALE_SMOOTH
                );
            
                lblFoto.setEnabled(true);
                lblFoto.setIcon(new ImageIcon(imgRedimensionada));
                lblFoto.setText("");
                
                pessoa.setFoto(bytesFoto);
            }
            catch(Exception e){
                JOptionPane.showConfirmDialog(this, e.getMessage());
            }
        }
    }//GEN-LAST:event_btnAddFotoActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if(lblNome.getText().isEmpty()||pessoa.getFoto() == null||pessoa.getCurriculo() == null){
            JOptionPane.showMessageDialog(this, "Insira todas as informações antes de salvar!");
            return;
        }
        
        pessoa.setNome(lblNome.getText());
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Salvar arquivo");
        chooser.setSelectedFile(new File(pessoa.getNome().toLowerCase()+".txt"));
        
        FileNameExtensionFilter filtro = new FileNameExtensionFilter("Arquivo de Texto (*.txt)", "txt");
        chooser.setFileFilter(filtro);
        
        int resultado = chooser.showSaveDialog(this);
        
        if(resultado==JFileChooser.APPROVE_OPTION){
            try{
                File arquivo = chooser.getSelectedFile();
                
                if(!arquivo.getName().toLowerCase().endsWith(".txt"))
                    arquivo = new File(arquivo.getAbsolutePath()+".txt");
                
                String textoSalvar = pessoa.getNome()+";"+pessoa.getFotoBase64()+";"+pessoa.getCurriculoBase64();
                Files.writeString(arquivo.toPath(), textoSalvar);
                
                JOptionPane.showMessageDialog(this, "Arquivo salvo com sucesso!");
            }
            catch(Exception e){
                JOptionPane.showMessageDialog(this, "Erro ao salvar o arquivo.\n"+e.getStackTrace().toString());
            }
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnCarregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCarregarActionPerformed
        // TODO add your handling code here:
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Carregar arquivo");
        
        FileNameExtensionFilter filtro = new FileNameExtensionFilter("Arquivo de Texto (*.txt)", "txt");
        chooser.setFileFilter(filtro);
        
        if(chooser.showOpenDialog(this)==JFileChooser.APPROVE_OPTION){
            try {
                String textoBruto = Files.readString(chooser.getSelectedFile().toPath());
                String[] textoFormado = textoBruto.split(";");
                
                String nomeCarregado = textoFormado[0].trim();
                byte[] fotoCarregada = Base64.getDecoder().decode(textoFormado[1].trim());
                byte[] curriculoCarregado = Base64.getDecoder().decode(textoFormado[2].trim());
                
                Pessoa pessoaCarregada = new Pessoa(nomeCarregado, fotoCarregada, curriculoCarregado);
                
                String letraCapitalizada = nomeCarregado.substring(0, 1).toUpperCase();
                String nomeCapitalizado = letraCapitalizada.concat(nomeCarregado.substring(1, nomeCarregado.length()));
                
                int largura = lblFoto.getWidth() > 0 ? lblFoto.getWidth() : 150;
                int altura = lblFoto.getHeight() > 0 ? lblFoto.getHeight() : 150;
                
                ImageIcon icon = new ImageIcon(pessoaCarregada.getFoto());
                Image img = icon.getImage().getScaledInstance(
                    largura, 
                    altura, 
                    Image.SCALE_SMOOTH
                );
                
                lblNome.setText(nomeCapitalizado);
                
                lblFoto.setText("");
                lblFoto.setIcon(new ImageIcon(img));
                lblFoto.setEnabled(true);
                
                lblCurriculo.setText("Currículo carregado.");
                
                JOptionPane.showMessageDialog(this, "Currículo carregado com sucesso!");
            } 
            catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro ao carregar o arquivo!\n");
            }
        }
    }//GEN-LAST:event_btnCarregarActionPerformed

